counters: dict[str, int] = {}

# Пороги "оттаивания": после N сообщений Нацуки становится мягче
TIER_THRESHOLDS = (5, 12, 25)  # -> уровни 1, 2, 3 (уровень 0 — самый колючий)


def load_state() -> None:
    try:
        if STATE_FILE.exists():
            data = json.loads(STATE_FILE.read_text(encoding="utf-8"))
            counters.update({str(k): int(v) for k, v in data.items()})
    except Exception as exc:  # повреждённый файл — просто начинаем с нуля
        logging.warning("Не удалось прочитать состояние: %s", exc)


def save_state() -> None:
    try:
        STATE_FILE.write_text(json.dumps(counters, ensure_ascii=False), encoding="utf-8")
    except Exception as exc:
        logging.warning("Не удалось сохранить состояние: %s", exc)


def bump(user_id: int) -> int:
    key = str(user_id)
    counters[key] = counters.get(key, 0) + 1
    save_state()
    return counters[key]


def tier_of(count: int) -> int:
    return sum(count >= t for t in TIER_THRESHOLDS)


