ZALGO = [chr(c) for c in range(0x0300, 0x0370)]


def glitch(text: str, intensity: float = 0.5) -> str:
    out = []
    for ch in text:
        out.append(ch)
        if ch.strip() and random.random() < intensity:
            out.append("".join(random.choice(ZALGO) for _ in range(random.randint(1, 4))))
    return "".join(out)


async def safe_edit(msg: Message, text: str) -> None:
    try:
        await msg.edit_text(text)
    except TelegramBadRequest:
        pass


