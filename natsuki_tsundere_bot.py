def build_reply(intent: str, tier: int) -> str:
    if intent == "compliment":
        return random.choice(COMPLIMENT[tier])

    pools = {
        "greeting": GREETING,
        "farewell": FAREWELL,
        "cupcake": CUPCAKE,
        "manga": MANGA,
        "yuri": YURI,
        "default": DEFAULT,
    }
    text = random.choice(pools[intent])
    # Чем выше уровень, тем чаще в конце добавляется «оттаявшая» фраза
    if tier > 0 and random.random() < 0.35 + 0.15 * tier:
        text += random.choice(SOFT_ADDONS[tier])
    return text


async def say(message: Message, text: str, markup=None) -> None:
    await message.bot.send_chat_action(message.chat.id, ChatAction.TYPING)
    await asyncio.sleep(random.uniform(0.4, 1.0))
    await message.answer(text, reply_markup=markup)


